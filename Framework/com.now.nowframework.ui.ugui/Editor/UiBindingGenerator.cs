using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;
using UnityEngine.UI;

namespace NowFrameWork.UI.Editor
{
    /// <summary>扫描层级、生成字段并在编辑器里写入引用；运行时不查找组件。</summary>
    public static class UiBindingGenerator
    {
        public sealed class Candidate
        {
            public string FieldName;
            public string TypeName;
            public string Path;
            public GameObject Target;
            public Component Component;
            public bool Explicit;
        }

        public sealed class Result
        {
            public string ScriptPath;
            public string ClassName;
            public bool ScriptCreated;
            public bool Bound;
            public int BoundCount;
            public int UnboundCount;
            public readonly List<string> Removed = new List<string>();
            public readonly List<Candidate> Fields = new List<Candidate>();
            public readonly List<string> Warnings = new List<string>();
        }

        const string Begin = "// <auto-generated>";
        const string End = "// </auto-generated>";
        const string EventsBegin = "// <auto-generated-events>";
        const string EventsEnd = "// </auto-generated-events>";
        const string UserBegin = "// <user-code>";
        const string UserEnd = "// </user-code>";

        static readonly (string Key, Type Type)[] Prefixes =
        {
            ("Button", typeof(Button)), ("Text", typeof(Text)), ("Image", typeof(Image)),
            ("Slider", typeof(Slider)), ("Toggle", typeof(Toggle)), ("Scroll", typeof(ScrollRect)),
            ("Input", typeof(InputField)), ("Rect", typeof(RectTransform)),
        };

        /// <summary>从标记名推断组件类型（[Button]name）。</summary>
        public static bool TryParsePrefix(string name, out Type type, out string rest)
        {
            foreach ((string key, Type candidate) in Prefixes)
            {
                string tag = "[" + key + "]";
                if (name.StartsWith(tag, StringComparison.Ordinal))
                {
                    type = candidate;
                    rest = name.Substring(tag.Length);
                    return true;
                }
            }

            Type tmp = Type.GetType("TMPro.TMP_Text, Unity.TextMeshPro");
            if (tmp != null && name.StartsWith("[TMP]", StringComparison.Ordinal))
            {
                type = tmp;
                rest = name.Substring(5);
                return true;
            }

            if (tmp != null && name.StartsWith("[TMPInput]", StringComparison.Ordinal))
            {
                type = Type.GetType("TMPro.TMP_InputField, Unity.TextMeshPro");
                rest = name.Substring(10);
                return true;
            }

            type = null;
            rest = name;
            return false;
        }

        /// <summary>按组件优先级推断字段类型。</summary>
        public static Component InferComponent(GameObject target, bool useTmp)
        {
            foreach ((string _, Type type) in Prefixes)
            {
                if (type == typeof(RectTransform)) continue;
                Component component = target.GetComponent(type);
                if (component != null) return component;
            }

            if (useTmp)
            {
                Type tmpText = Type.GetType("TMPro.TMP_Text, Unity.TextMeshPro");
                Type tmpInput = Type.GetType("TMPro.TMP_InputField, Unity.TextMeshPro");

                if (tmpInput != null)
                {
                    Component input = target.GetComponent(tmpInput);
                    if (input != null) return input;
                }

                if (tmpText != null)
                {
                    Component text = target.GetComponent(tmpText);
                    if (text != null) return text;
                }
            }

            return null;
        }

        /// <summary>把节点名转成合法字段名。</summary>
        public static string Sanitize(string raw, bool lowerFirst)
        {
            var builder = new StringBuilder(raw.Length);

            foreach (char c in raw)
            {
                bool valid = char.IsLetterOrDigit(c) || c == '_';
                builder.Append(valid ? c : '_');
            }

            string value = builder.ToString().Trim('_');
            if (value.Length == 0) value = "field";
            if (char.IsDigit(value[0])) value = "_" + value;

            if (lowerFirst) value = char.ToLowerInvariant(value[0]) + value.Substring(1);
            return value;
        }

        /// <summary>扫描层级，返回将要生成的字段（不修改任何资产）。</summary>
        public static Result Scan(GameObject root, UiBindingOptions options)
        {
            var result = new Result();
            var used = new HashSet<string>();

            if (root == null)
            {
                result.Warnings.Add("未选中对象。");
                return result;
            }

            foreach (Transform child in root.GetComponentsInChildren<Transform>(true))
            {
                if (child == root.transform) continue;

                GameObject go = child.gameObject;
                Component component;
                Type explicitType;
                string rest;

                if (TryParsePrefix(go.name, out explicitType, out rest))
                {
                    component = go.GetComponent(explicitType);
                    if (component == null)
                    {
                        result.Warnings.Add(go.name + "：标记要求 " + explicitType.Name + "，但节点上没有该组件。");
                        continue;
                    }
                }
                else
                {
                    if (!options.InferUnmarked) continue;
                    component = InferComponent(go, options.UseTextMeshPro);
                    rest = go.name;
                    if (component == null) continue;
                }

                string field = Sanitize(rest, options.LowerFirst);
                string unique = field;
                int index = 2;

                while (!used.Add(unique)) unique = field + index++;

                result.Fields.Add(new Candidate
                {
                    FieldName = unique,
                    TypeName = component.GetType().Name,
                    Path = PathOf(root.transform, child),
                    Target = go,
                    Component = component,
                    Explicit = explicitType != null,
                });
            }

            UiView view = root.GetComponent<UiView>();

            if (view != null)
            {
                var serialized = new SerializedObject(view);

                foreach (Candidate candidate in result.Fields)
                {
                    SerializedProperty property = serialized.FindProperty(candidate.FieldName);

                    if (property != null && property.objectReferenceValue != null) result.BoundCount++;
                    else result.UnboundCount++;
                }
            }

            return result;
        }

        /// <summary>生成或刷新脚本，并在编辑器里写入引用。Prefab 资产会走 PrefabContents。</summary>
        public static Result Generate(GameObject target, UiBindingOptions options)
        {
            if (target == null) throw new ArgumentNullException(nameof(target));

            string assetPath = AssetDatabase.GetAssetPath(target);
            bool prefabAsset = !string.IsNullOrEmpty(assetPath) && assetPath.EndsWith(".prefab", StringComparison.OrdinalIgnoreCase);

            if (!prefabAsset) return GenerateInternal(target, options, null);

            GameObject contents = PrefabUtility.LoadPrefabContents(assetPath);

            try
            {
                Result result = GenerateInternal(contents, options, assetPath);
                PrefabUtility.SaveAsPrefabAsset(contents, assetPath);
                return result;
            }
            finally
            {
                PrefabUtility.UnloadPrefabContents(contents);
            }
        }

        static Result GenerateInternal(GameObject root, UiBindingOptions options, string prefabPath)
        {
            Result result = Scan(root, options);

            UiView view = root.GetComponent<UiView>();
            string scriptPath = null;
            bool replaceBaseView = false;

            if (view != null)
            {
                MonoScript script = MonoScript.FromMonoBehaviour(view);
                scriptPath = script != null ? AssetDatabase.GetAssetPath(script) : null;
                result.ClassName = view.GetType().Name;
            }

            if (scriptPath != null && IsFrameworkScript(scriptPath))
            {
                result.Warnings.Add("选中的对象使用框架脚本 " + scriptPath + "，不会改写包内文件。" +
                    "请先给该面板挂一个项目自己的 UiView 派生脚本，再执行生成。");
                return result;
            }

            if (view != null && view.GetType() == typeof(UiView))
            {
                replaceBaseView = true;
                view = null;
                scriptPath = null;
            }

            if (string.IsNullOrEmpty(scriptPath))
            {
                EnsureAssemblyDefinition(options.Folder, options.UseTextMeshPro);

                string baseName = Sanitize(root.name, false);

                if (!baseName.EndsWith("View", StringComparison.OrdinalIgnoreCase)) baseName += "View";

                result.ClassName = baseName;
                scriptPath = options.Folder.TrimEnd('/') + "/" + result.ClassName + ".cs";

                int suffix = 2;

                while (File.Exists(scriptPath) && !FileHasClass(scriptPath, result.ClassName))
                {
                    result.ClassName = baseName + suffix++;
                    scriptPath = options.Folder.TrimEnd('/') + "/" + result.ClassName + ".cs";
                }
            }

            result.ScriptPath = scriptPath;
            CollectRemoved(scriptPath, result);
            string block = BuildBlock(result.Fields, options);
            string events = BuildEvents(result.Fields, options);
            string user = BuildUser(result.Fields, options);
            bool created = WriteScript(scriptPath, result.ClassName, options, block, events, user, result.Warnings);
            result.ScriptCreated = created;

            AssetDatabase.ImportAsset(scriptPath);
            AssetDatabase.Refresh();

            if (view == null)
            {
                MonoScript script = AssetDatabase.LoadAssetAtPath<MonoScript>(scriptPath);
                Type type = script != null ? script.GetClass() : null;

                if (type == null)
                {
                    result.Warnings.Add("脚本已生成，正在等待编译；完成后会自动挂载并写入引用。");
                    UiBindingAutoBinder.Queue(prefabPath, root, options.Namespace + "." + result.ClassName, result);
                    return result;
                }

                if (replaceBaseView)
                {
                    UiView baseView = root.GetComponent<UiView>();
                    if (baseView != null) UnityEngine.Object.DestroyImmediate(baseView, true);
                }

                view = root.AddComponent(type) as UiView;
                if (view == null) throw new InvalidOperationException("生成类型不是 UiView：" + type.FullName);
            }

            if (options.BindAfterGenerate) Bind(root, view, result, prefabPath);
            else result.Warnings.Add("已跳过引用绑定（选项关闭）。");

            return result;
        }

        static void Bind(GameObject root, UiView view, Result result, string prefabPath)
        {
            Undo.RegisterCompleteObjectUndo(view, "Bind UI Fields");

            var serialized = new SerializedObject(view);
            bool dirty = false;
            bool missing = false;

            foreach (Candidate candidate in result.Fields)
            {
                SerializedProperty property = serialized.FindProperty(candidate.FieldName);

                if (property == null)
                {
                    result.Warnings.Add("字段 " + candidate.FieldName + " 尚未编译，编译完成后会自动绑定。");
                    missing = true;
                    continue;
                }

                if (property.objectReferenceValue != null) result.BoundCount++;
                else result.UnboundCount++;

                property.objectReferenceValue = candidate.Component;
                dirty = true;
            }

            if (dirty) serialized.ApplyModifiedPropertiesWithoutUndo();

            EditorUtility.SetDirty(view);

            if (root.scene.IsValid()) UnityEditor.SceneManagement.EditorSceneManager.MarkSceneDirty(root.scene);

            if (missing)
                UiBindingAutoBinder.Queue(prefabPath, root, view.GetType().FullName, result);

            result.Bound = dirty || missing;
        }

        static void CollectRemoved(string path, Result result)
        {
            if (!File.Exists(path)) return;

            string existing = File.ReadAllText(path);
            int begin = existing.IndexOf(Begin, StringComparison.Ordinal);
            int end = existing.IndexOf(End, StringComparison.Ordinal);

            if (begin < 0 || end <= begin) return;

            var names = new HashSet<string>();

            foreach (Candidate candidate in result.Fields)
                names.Add(candidate.FieldName);

            string region = existing.Substring(begin, end - begin);

            foreach (string line in region.Split('\n'))
            {
                int semicolon = line.IndexOf(';');

                if (semicolon < 0) continue;

                string trimmed = line.Substring(0, semicolon).Trim();
                int space = trimmed.LastIndexOf(' ');

                if (space < 0) continue;

                string name = trimmed.Substring(space + 1).Trim();

                if (name.Length == 0 || !char.IsLetter(name[0])) continue;
                if (names.Contains(name)) continue;

                result.Removed.Add(name);
            }
        }

        static string BuildBlock(List<Candidate> fields, UiBindingOptions options)
        {
            var builder = new StringBuilder();
            builder.Append("        ").Append(Begin).AppendLine();

            string group = null;

            foreach (Candidate field in fields)
            {
                if (options.GroupByHierarchy)
                {
                    int slash = field.Path.LastIndexOf('/');
                    string current = slash > 0 ? field.Path.Substring(0, slash) : string.Empty;

                    if (current != group)
                    {
                        if (group != null) builder.AppendLine("        #endregion");
                        group = current;
                        builder.AppendLine("        #region " + (group.Length == 0 ? "(root)" : group));
                    }
                }

                builder.Append("        ").AppendLine(options.FieldDeclaration(field.TypeName, field.FieldName));
            }

            if (group != null) builder.AppendLine("        #endregion");

            builder.Append("        ").Append(End);
            return builder.ToString();
        }

        static string BuildEvents(List<Candidate> fields, UiBindingOptions options)
        {
            if (!options.GenerateEvents) return string.Empty;

            var buttons = new List<Candidate>();

            foreach (Candidate field in fields)
                if (field.TypeName == "Button") buttons.Add(field);

            if (buttons.Count == 0) return string.Empty;

            var builder = new StringBuilder();
            builder.Append("        ").Append(EventsBegin).AppendLine();
            builder.AppendLine("        protected override void OnCreate()");
            builder.AppendLine("        {");

            foreach (Candidate button in buttons)
            {
                builder.AppendLine("            if (" + button.FieldName + " != null) " + button.FieldName +
                    ".onClick.AddListener(() => On" + Capitalize(button.FieldName) + "Clicked());");
            }

            builder.AppendLine("        }");
            builder.Append("        ").Append(EventsEnd);
            return builder.ToString();
        }

        static string BuildUser(List<Candidate> fields, UiBindingOptions options)
        {
            var builder = new StringBuilder();
            builder.Append("        ").Append(UserBegin).AppendLine();

            foreach (Candidate field in fields)
            {
                if (field.TypeName != "Button") continue;

                builder.AppendLine("        partial void On" + Capitalize(field.FieldName) + "Clicked();");
            }

            if (options.GenerateLifecycle)
            {
                builder.AppendLine();
                builder.AppendLine("        protected override Cysharp.Threading.Tasks.UniTask OnOpenAsync(object args, System.Threading.CancellationToken ct)");
                builder.AppendLine("            => Cysharp.Threading.Tasks.UniTask.CompletedTask;");
                builder.AppendLine();
                builder.AppendLine("        protected override Cysharp.Threading.Tasks.UniTask OnCloseAsync()");
                builder.AppendLine("            => Cysharp.Threading.Tasks.UniTask.CompletedTask;");
            }

            builder.Append("        ").Append(UserEnd);
            return builder.ToString();
        }

        static string Capitalize(string value)
        {
            return string.IsNullOrEmpty(value) ? value : char.ToUpperInvariant(value[0]) + value.Substring(1);
        }

        static bool WriteScript(string path, string className, UiBindingOptions options, string block,
            string events, string user, List<string> warnings)
        {
            if (File.Exists(path))
            {
                string existing = File.ReadAllText(path).Replace("\r\n", "\n");

                int begin = existing.IndexOf(Begin, StringComparison.Ordinal);
                int end = existing.IndexOf(End, StringComparison.Ordinal);

                if (begin < 0 || end <= begin)
                {
                    int insert = FindClassEnd(existing, className);

                    if (insert < 0)
                    {
                        warnings.Add("脚本缺少 auto-generated 标记且无法定位类结尾，已跳过更新：" + path);
                        return false;
                    }

                    string injected = existing.Insert(insert, block + "\n" + user + "\n");
                    File.WriteAllText(path, injected);
                    warnings.Add("已向现有脚本插入绑定块；如需自定义命名请手动整理。");
                    return false;
                }

                string updated = existing.Substring(0, begin) + block.TrimStart() + existing.Substring(end + End.Length);

                if (!string.IsNullOrEmpty(events))
                {
                    int eventsBegin = updated.IndexOf(EventsBegin, StringComparison.Ordinal);
                    int eventsEnd = eventsBegin >= 0 ? updated.IndexOf(EventsEnd, eventsBegin, StringComparison.Ordinal) : -1;

                    if (eventsBegin >= 0 && eventsEnd > eventsBegin)
                        updated = updated.Substring(0, eventsBegin) + events.TrimStart() +
                            updated.Substring(eventsEnd + EventsEnd.Length);
                    else
                        updated = InsertAfter(updated, End, "\n" + events);
                }

                int userBegin = updated.IndexOf(UserBegin, StringComparison.Ordinal);
                int userEnd = userBegin >= 0 ? updated.IndexOf(UserEnd, userBegin, StringComparison.Ordinal) : -1;

                if (userBegin >= 0 && userEnd > userBegin)
                {
                    string additions = BuildAdditions(updated, user);
                    if (additions.Length > 0)
                        updated = updated.Insert(userEnd, additions + "\n");
                }
                else
                {
                    int insert = FindClassEnd(updated, className);
                    if (insert >= 0) updated = updated.Insert(insert, user + "\n");
                }

                File.WriteAllText(path, updated);
                return false;
            }

            string usings = "using UnityEngine;\nusing UnityEngine.UI;\n";
            if (options.UseTextMeshPro) usings += "using TMPro;\n";

            string content =
                "// 由 NowFrameWork UI 绑定生成器创建。手写代码请放在 user-code 区块内。\n" +
                usings + "\n" +
                "namespace " + options.Namespace + "\n{\n" +
                "    public partial class " + className + " : NowFrameWork.UI.UiView\n    {\n" +
                block + "\n\n" + events + "\n\n" + user + "\n    }\n}\n";

            Directory.CreateDirectory(Path.GetDirectoryName(path));
            File.WriteAllText(path, content);
            return true;
        }

        static string BuildAdditions(string existing, string user)
        {
            var additions = new StringBuilder();
            string[] lines = user.Split('\n');

            foreach (string line in lines)
            {
                string trimmed = line.Trim();

                if (!trimmed.StartsWith("partial void ", StringComparison.Ordinal) &&
                    !trimmed.StartsWith("protected override Cysharp", StringComparison.Ordinal))
                    continue;

                string identifier;

                if (trimmed.StartsWith("partial void ", StringComparison.Ordinal))
                {
                    identifier = trimmed.Substring(13).Split('(')[0];
                }
                else
                {
                    int nameStart = trimmed.IndexOf("UniTask ", StringComparison.Ordinal) + 8;
                    int paren = trimmed.IndexOf('(', nameStart);
                    identifier = paren > nameStart ? trimmed.Substring(nameStart, paren - nameStart) : "OnOpenAsync";
                }

                if (existing.Contains(identifier, StringComparison.Ordinal)) continue;

                additions.AppendLine(line);
            }

            return additions.ToString().TrimEnd('\n');
        }

        static string InsertAfter(string text, string marker, string content)
        {
            int index = text.IndexOf(marker, StringComparison.Ordinal);
            return index < 0 ? text : text.Insert(index + marker.Length, content);
        }

        /// <summary>输出目录不在任何 asmdef 内时，创建引用框架 UI 的程序集定义。</summary>
        static void EnsureAssemblyDefinition(string folder, bool useTmp)
        {
            string directory = folder.TrimEnd('/');

            for (string current = directory; current.StartsWith("Assets", StringComparison.Ordinal);)
            {
                if (Directory.GetFiles(current, "*.asmdef").Length > 0) return;

                string parent = Path.GetDirectoryName(current);
                if (string.IsNullOrEmpty(parent)) break;

                current = parent.Replace('\\', '/');
            }

            string path = directory + "/NowFrameWork.UI.Generated.asmdef";
            if (File.Exists(path)) return;

            string references = "\"NowFrameWork.UI.UGUI\", \"UnityEngine.UI\", \"UniTask\"";
            if (useTmp) references += ", \"Unity.TextMeshPro\"";

            string json = "{\n" +
                "  \"name\": \"NowFrameWork.UI.Generated\",\n" +
                "  \"rootNamespace\": \"\",\n" +
                "  \"references\": [" + references + "],\n" +
                "  \"includePlatforms\": [],\n" +
                "  \"excludePlatforms\": [],\n" +
                "  \"allowUnsafeCode\": false,\n" +
                "  \"overrideReferences\": false,\n" +
                "  \"precompiledReferences\": [],\n" +
                "  \"autoReferenced\": false,\n" +
                "  \"defineConstraints\": [],\n" +
                "  \"versionDefines\": [],\n" +
                "  \"noEngineReferences\": false\n" +
                "}\n";

            Directory.CreateDirectory(directory);
            File.WriteAllText(path, json);
            AssetDatabase.ImportAsset(path);
            Debug.Log("[UI 绑定] 已创建程序集定义：" + path);
        }

        static bool FileHasClass(string path, string className)
        {
            try
            {
                return File.ReadAllText(path).Contains("class " + className, StringComparison.Ordinal);
            }
            catch
            {
                return false;
            }
        }

        static bool IsFrameworkScript(string path)
        {
            return !string.IsNullOrEmpty(path) &&
                (path.StartsWith("Packages/", StringComparison.Ordinal) ||
                 path.Contains("com.now.nowframework."));
        }

        static int FindClassEnd(string text, string className)
        {
            int start = text.IndexOf("class " + className, StringComparison.Ordinal);
            if (start < 0) return -1;

            int open = text.IndexOf('{', start);
            if (open < 0) return -1;

            int depth = 0;

            for (int i = open; i < text.Length; i++)
            {
                if (text[i] == '{') depth++;
                else if (text[i] == '}')
                {
                    depth--;
                    if (depth == 0) return i;
                }
            }

            return -1;
        }

        static string PathOf(Transform root, Transform target)
        {
            var parts = new List<string>();
            Transform current = target;

            while (current != null && current != root)
            {
                parts.Insert(0, current.name);
                current = current.parent;
            }

            return string.Join("/", parts);
        }
    }
