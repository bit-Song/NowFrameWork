using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;
using UnityEngine.UI;

namespace NowFrameWork.UI.Editor
{
    /// <summary>扫描层级、生成字段并在编辑器里写入引用；运行时不查找组件。</summary>
    public static class UiBindingGenerator
    {
        public sealed class Candidate
        {
            public string FieldName;
            public string TypeName;
            public string Path;
            public GameObject Target;
            public Component Component;
            public bool Explicit;
        }

        public sealed class Result
        {
            public string ScriptPath;
            public string ClassName;
            public bool ScriptCreated;
            public bool Bound;
            public readonly List<Candidate> Fields = new List<Candidate>();
            public readonly List<string> Warnings = new List<string>();
        }

        const string Begin = "// <auto-generated>";
        const string End = "// </auto-generated>";

        static readonly (string Key, Type Type)[] Prefixes =
        {
            ("Button", typeof(Button)), ("Text", typeof(Text)), ("Image", typeof(Image)),
            ("Slider", typeof(Slider)), ("Toggle", typeof(Toggle)), ("Scroll", typeof(ScrollRect)),
            ("Input", typeof(InputField)), ("Rect", typeof(RectTransform)),
        };

        /// <summary>从标记名推断组件类型（[Button]name）。</summary>
        public static bool TryParsePrefix(string name, out Type type, out string rest)
        {
            foreach ((string key, Type candidate) in Prefixes)
            {
                string tag = "[" + key + "]";
                if (name.StartsWith(tag, StringComparison.Ordinal))
                {
                    type = candidate;
                    rest = name.Substring(tag.Length);
                    return true;
                }
            }

            Type tmp = Type.GetType("TMPro.TMP_Text, Unity.TextMeshPro");
            if (tmp != null && name.StartsWith("[TMP]", StringComparison.Ordinal))
            {
                type = tmp;
                rest = name.Substring(5);
                return true;
            }

            if (tmp != null && name.StartsWith("[TMPInput]", StringComparison.Ordinal))
            {
                type = Type.GetType("TMPro.TMP_InputField, Unity.TextMeshPro");
                rest = name.Substring(10);
                return true;
            }

            type = null;
            rest = name;
            return false;
        }

        /// <summary>按组件优先级推断字段类型。</summary>
        public static Component InferComponent(GameObject target, bool useTmp)
        {
            foreach ((string _, Type type) in Prefixes)
            {
                if (type == typeof(RectTransform)) continue;
                Component component = target.GetComponent(type);
                if (component != null) return component;
            }

            if (useTmp)
            {
                Type tmpText = Type.GetType("TMPro.TMP_Text, Unity.TextMeshPro");
                Type tmpInput = Type.GetType("TMPro.TMP_InputField, Unity.TextMeshPro");

                if (tmpInput != null)
                {
                    Component input = target.GetComponent(tmpInput);
                    if (input != null) return input;
                }

                if (tmpText != null)
                {
                    Component text = target.GetComponent(tmpText);
                    if (text != null) return text;
                }
            }

            return null;
        }

        /// <summary>把节点名转成合法字段名。</summary>
        public static string Sanitize(string raw, bool lowerFirst)
        {
            var builder = new StringBuilder(raw.Length);

            foreach (char c in raw)
            {
                bool valid = char.IsLetterOrDigit(c) || c == '_';
                builder.Append(valid ? c : '_');
            }

            string value = builder.ToString().Trim('_');
            if (value.Length == 0) value = "field";
            if (char.IsDigit(value[0])) value = "_" + value;

            if (lowerFirst) value = char.ToLowerInvariant(value[0]) + value.Substring(1);
            return value;
        }

        /// <summary>扫描层级，返回将要生成的字段（不修改任何资产）。</summary>
        public static Result Scan(GameObject root, UiBindingOptions options)
        {
            var result = new Result();
            var used = new HashSet<string>();

            if (root == null)
            {
                result.Warnings.Add("未选中对象。");
                return result;
            }

            foreach (Transform child in root.GetComponentsInChildren<Transform>(true))
            {
                if (child == root.transform) continue;

                GameObject go = child.gameObject;
                Component component;
                Type explicitType;
                string rest;

                if (TryParsePrefix(go.name, out explicitType, out rest))
                {
                    component = go.GetComponent(explicitType);
                    if (component == null)
                    {
                        result.Warnings.Add(go.name + "：标记要求 " + explicitType.Name + "，但节点上没有该组件。");
                        continue;
                    }
                }
                else
                {
                    component = InferComponent(go, options.UseTextMeshPro);
                    rest = go.name;
                    if (component == null) continue;
                }

                string field = Sanitize(rest, options.LowerFirst);
                string unique = field;
                int index = 2;

                while (!used.Add(unique)) unique = field + index++;

                result.Fields.Add(new Candidate
                {
                    FieldName = unique,
                    TypeName = component.GetType().Name,
                    Path = PathOf(root.transform, child),
                    Target = go,
                    Component = component,
                    Explicit = explicitType != null,
                });
            }

            return result;
        }

        /// <summary>生成或刷新脚本，并在编辑器里写入引用。Prefab 资产会走 PrefabContents。</summary>
        public static Result Generate(GameObject target, UiBindingOptions options)
        {
            if (target == null) throw new ArgumentNullException(nameof(target));

            string assetPath = AssetDatabase.GetAssetPath(target);
            bool prefabAsset = !string.IsNullOrEmpty(assetPath) && assetPath.EndsWith(".prefab", StringComparison.OrdinalIgnoreCase);

            if (!prefabAsset) return GenerateInternal(target, options);

            GameObject contents = PrefabUtility.LoadPrefabContents(assetPath);

            try
            {
                Result result = GenerateInternal(contents, options);
                PrefabUtility.SaveAsPrefabAsset(contents, assetPath);
                return result;
            }
            finally
            {
                PrefabUtility.UnloadPrefabContents(contents);
            }
        }

        static Result GenerateInternal(GameObject root, UiBindingOptions options)
        {
            Result result = Scan(root, options);

            UiView view = root.GetComponent<UiView>();
            string scriptPath = null;

            if (view != null)
            {
                MonoScript script = MonoScript.FromMonoBehaviour(view);
                scriptPath = script != null ? AssetDatabase.GetAssetPath(script) : null;
                result.ClassName = view.GetType().Name;
            }

            if (string.IsNullOrEmpty(scriptPath))
            {
                result.ClassName = Sanitize(root.name, false) + "View";
                scriptPath = options.Folder.TrimEnd('/') + "/" + result.ClassName + ".cs";
            }

            result.ScriptPath = scriptPath;
            string block = BuildBlock(result.Fields, options);
            bool created = WriteScript(scriptPath, result.ClassName, options, block, result.Warnings);
            result.ScriptCreated = created;

            AssetDatabase.ImportAsset(scriptPath);
            AssetDatabase.Refresh();

            if (view == null)
            {
                MonoScript script = AssetDatabase.LoadAssetAtPath<MonoScript>(scriptPath);
                Type type = script != null ? script.GetClass() : null;

                if (type == null)
                {
                    result.Warnings.Add("脚本已生成，但尚未编译完成；编译后再执行一次即可自动绑定引用。");
                    return result;
                }

                view = root.AddComponent(type) as UiView;
                if (view == null) throw new InvalidOperationException("生成类型不是 UiView：" + type.FullName);
            }

            if (options.BindAfterGenerate) Bind(root, view, result);
            else result.Warnings.Add("已跳过引用绑定（选项关闭）。");

            return result;
        }

        static void Bind(GameObject root, UiView view, Result result)
        {
            Undo.RegisterCompleteObjectUndo(view, "Bind UI Fields");

            var serialized = new SerializedObject(view);
            bool dirty = false;

            foreach (Candidate candidate in result.Fields)
            {
                SerializedProperty property = serialized.FindProperty(candidate.FieldName);

                if (property == null)
                {
                    result.Warnings.Add("字段不存在：" + candidate.FieldName + "（可能刚改名，重新生成一次）。");
                    continue;
                }

                property.objectReferenceValue = candidate.Component;
                dirty = true;
            }

            if (dirty) serialized.ApplyModifiedPropertiesWithoutUndo();

            EditorUtility.SetDirty(view);

            if (root.scene.IsValid()) UnityEditor.SceneManagement.EditorSceneManager.MarkSceneDirty(root.scene);

            result.Bound = dirty;
        }

        static string BuildBlock(List<Candidate> fields, UiBindingOptions options)
        {
            var builder = new StringBuilder();
            builder.Append("        ").Append(Begin).AppendLine();

            foreach (Candidate field in fields)
                builder.Append("        ").AppendLine(options.FieldDeclaration(field.TypeName, field.FieldName));

            builder.Append("        ").Append(End);
            return builder.ToString();
        }

        static bool WriteScript(string path, string className, UiBindingOptions options, string block, List<string> warnings)
        {
            if (File.Exists(path))
            {
                string existing = File.ReadAllText(path).Replace("\r\n", "\n");
                int begin = existing.IndexOf(Begin, StringComparison.Ordinal);
                int end = existing.IndexOf(End, StringComparison.Ordinal);

                if (begin >= 0 && end > begin)
                {
                    string updated = existing.Substring(0, begin) + block.TrimStart() + existing.Substring(end + End.Length);
                    File.WriteAllText(path, updated);
                    return false;
                }

                int insert = existing.LastIndexOf('}');
                if (insert < 0) throw new InvalidOperationException("脚本结构异常，找不到类结束位置：" + path);

                string injected = existing.Insert(insert, block + "\n");
                File.WriteAllText(path, injected);
                warnings.Add("已向现有脚本插入绑定块；如需自定义命名请手动整理。");
                return false;
            }

            string usings = "using UnityEngine;\nusing UnityEngine.UI;\n";
            if (options.UseTextMeshPro) usings += "using TMPro;\n";

            string content =
                "// 由 NowFrameWork UI 绑定生成器创建。手写代码请放在绑定块之外。\n" +
                usings + "\n" +
                "namespace " + options.Namespace + "\n{\n" +
                "    public partial class " + className + " : NowFrameWork.UI.UiView\n    {\n" +
                block + "\n    }\n}\n";

            Directory.CreateDirectory(Path.GetDirectoryName(path));
            File.WriteAllText(path, content);
            return true;
        }

        static string PathOf(Transform root, Transform target)
        {
            var parts = new List<string>();
            Transform current = target;

            while (current != null && current != root)
            {
                parts.Insert(0, current.name);
                current = current.parent;
            }

            return string.Join("/", parts);
        }
    }
}
