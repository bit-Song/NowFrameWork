using System;
using System.Collections.Generic;
using System.IO;
using System.Text;

namespace NowFrameWork.EditorTools.AssetKeys
{
    // 纯数据代码生成，不读取或写入工程；冲突时绝不产出可写入的源码。
    internal static class AssetKeySource
    {
        internal sealed class Entry
        {
            public string Path;
            public string Address;
            public string Group;
            public string Symbol;
        }

        internal sealed class Plan
        {
            public readonly List<Entry> Entries = new List<Entry>();
            public readonly List<string> Errors = new List<string>();
            public string Source;
        }

        sealed class Node
        {
            public string Origin;
            public string Segment;
            public Entry Asset;
            public readonly SortedDictionary<string, Node> Children = new SortedDictionary<string, Node>(StringComparer.Ordinal);
        }

        const string Keywords = " abstract as base bool break byte case catch char checked class const continue decimal default delegate do double else enum event explicit extern false finally fixed float for foreach goto if implicit in int interface internal is lock long namespace new null object operator out override params private protected public readonly ref return sbyte sealed short sizeof stackalloc static string struct switch this throw true try typeof uint ulong unchecked unsafe ushort using virtual void volatile while record required file scoped " ;
        internal const string Marker = "// <auto-generated by NowFrameWork.AssetKeys>";

        internal static Plan Build(IEnumerable<Entry> input, string root, string nameSpace)
        {
            var plan = new Plan();
            root = (root ?? "").Replace('\\', '/').TrimEnd('/');
            if (root != "Assets" && !root.StartsWith("Assets/", StringComparison.Ordinal))
                plan.Errors.Add("资源根目录必须位于 Assets 下");
            if (root.Contains("/../") || root.EndsWith("/..", StringComparison.Ordinal) || root.Contains("//"))
                plan.Errors.Add("根目录不能包含 .. 或空路径段");
            foreach (string part in (nameSpace ?? "").Split('.'))
                if (part.Length == 0 || Identifier(part) != part)
                    plan.Errors.Add("命名空间不是合法 C# 标识符: " + nameSpace);
            if (plan.Errors.Count != 0) return plan;
            foreach (Entry entry in input)
            {
                if (entry.Path == null || !entry.Path.StartsWith(root + "/", StringComparison.Ordinal)) continue;
                plan.Entries.Add(new Entry { Path = entry.Path, Address = entry.Address, Group = entry.Group });
            }
            plan.Entries.Sort((a, b) => StringComparer.Ordinal.Compare(a.Path, b.Path));
            var tree = new Node();
            var addresses = new Dictionary<string, string>(StringComparer.Ordinal);
            foreach (Entry entry in plan.Entries) AddEntry(tree, addresses, entry, root, plan.Errors);
            if (plan.Entries.Count == 0) plan.Errors.Add("根目录下没有已登记且参与构建的 Addressables 资源");
            if (plan.Errors.Count != 0) return plan;
            var code = new StringBuilder(Marker + "\n// 请勿手动修改；由 Addressables 已登记资源路径生成，值保留原 Address。\nnamespace " + nameSpace + "\n{\n    public static class AssetKeys\n    {\n");
            WriteTree(code, tree, 2);
            code.Append("    }\n}\n");
            plan.Source = code.ToString();
            return plan;
        }

        static void AddEntry(Node tree, Dictionary<string, string> addresses, Entry entry, string root, List<string> errors)
        {
            string origin = entry.Path + " [Group: " + entry.Group + "]";
            if (string.IsNullOrWhiteSpace(entry.Address)) { errors.Add("Address 为空: " + origin); return; }
            if (addresses.TryGetValue(entry.Address, out string previous))
                errors.Add("Address 重复 '" + entry.Address + "':\n" + previous + "\n" + origin);
            else addresses.Add(entry.Address, origin);
            string relative = entry.Path.Substring(root.Length + 1);
            string extension = Path.GetExtension(relative);
            if (extension.Length == 0) { errors.Add("资源缺少扩展名: " + origin); return; }
            string[] parts = relative.Split('/');
            parts[parts.Length - 1] = Path.GetFileNameWithoutExtension(relative) + "_" + extension.Substring(1);
            var symbols = new string[parts.Length];
            Node parent = tree;
            string parentName = "AssetKeys";
            for (int i = 0; i < parts.Length; i++)
            {
                string name = Identifier(parts[i]);
                symbols[i] = name;
                if (name == parentName) { errors.Add("成员与所属类型同名 '" + name + "': " + origin); return; }
                bool leaf = i == parts.Length - 1;
                if (!parent.Children.TryGetValue(name, out Node node))
                {
                    node = new Node { Origin = origin, Segment = parts[i] };
                    parent.Children.Add(name, node);
                }
                else if (node.Asset != null || leaf || node.Segment != parts[i])
                {
                    errors.Add("代码引用冲突 'AssetKeys." + string.Join(".", symbols, 0, i + 1) + "':\n" + node.Origin + "\n" + origin);
                    return;
                }
                if (leaf) node.Asset = entry;
                parent = node;
                parentName = name;
            }
            entry.Symbol = "AssetKeys." + string.Join(".", symbols);
        }

        internal static string Identifier(string value)
        {
            var result = new StringBuilder();
            foreach (char c in value) result.Append(char.IsLetterOrDigit(c) || c == '_' ? c : '_');
            if (result.Length == 0) result.Append('_');
            if (!char.IsLetter(result[0]) && result[0] != '_') result.Insert(0, '_');
            if (Keywords.Contains(" " + result + " ")) result.Insert(0, '_');
            return result.ToString();
        }

        static void WriteTree(StringBuilder code, Node parent, int depth)
        {
            string indent = new string(' ', depth * 4);
            foreach (KeyValuePair<string, Node> pair in parent.Children)
            {
                Node node = pair.Value;
                if (node.Asset != null)
                    code.Append(indent).Append("public static readonly global::NowFrameWork.Assets.AssetKey ")
                        .Append(pair.Key).Append(" = global::NowFrameWork.Assets.AssetKey.From(\"")
                        .Append(Escape(node.Asset.Address)).Append("\");\n");
                else
                {
                    code.Append(indent).Append("public static class ").Append(pair.Key).Append("\n").Append(indent).Append("{\n");
                    WriteTree(code, node, depth + 1);
                    code.Append(indent).Append("}\n");
                }
            }
        }

        static string Escape(string value)
        {
            var result = new StringBuilder();
            foreach (char c in value)
            {
                if (c == '\\' || c == '"') result.Append('\\').Append(c);
                else if (char.IsControl(c) || c == '\u2028' || c == '\u2029') result.Append("\\u").Append(((int)c).ToString("x4"));
                else result.Append(c);
            }
            return result.ToString();
        }
    }
}
